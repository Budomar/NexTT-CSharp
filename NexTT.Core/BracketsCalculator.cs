    private sealed record Rule(string ConnectionGroup, string MountType,
        string[] Types, int LengthMin, int LengthMax, int HeightMin, int HeightMax,
        int Qty, string Article);

    public static IReadOnlyList<(string Article, int Quantity)> Calculate(
        string? radiatorType, int length, int height, string? bracketType,
        string? connection = "VK-правое", int quantity = 1)
    {
        if (bracketType == "Без кронштейнов")
            return Array.Empty<(string Article, int Quantity)>();

        string group = GetConnectionGroup(connection);
        string? mount = GetMountType(bracketType);
        if (mount is null)
            return Array.Empty<(string Article, int Quantity)>();

        Rule[] rules = (group, mount) switch
        {
            ("VK_K", "настенный") => WallVkKRules,
            ("VK_K", "напольный") => FloorVkKRules,
            ("HV_H", "настенный") => WallHvHRules,
            _ => FloorHvHRules
        };

        var result = new List<(string Article, int Quantity)>();
        foreach (Rule rule in rules)
            if (Matches(rule, radiatorType, length, height))
                result.Add((rule.Article, rule.Qty * quantity));
        // No sorting, grouping or filtering of zero/negative quantities.
        return result;
    }

    public static IReadOnlyList<(string Article, int Quantity)> CalculateForManual(
        string? radiatorType, int length, int height, string? bracketType,
        string? connection = "VK-правое", int quantity = 1)
    {
        if (bracketType == "Без кронштейнов")
            return Array.Empty<(string Article, int Quantity)>();

        string group = GetConnectionGroup(connection);
        string? mount = GetMountType(bracketType);
        if (mount is null)
            return Array.Empty<(string Article, int Quantity)>();

        var result = new List<(string Article, int Quantity)>();
        foreach (Rule rule in ManualCompatibilityRules)
            if (rule.ConnectionGroup == group && rule.MountType == mount &&
                Matches(rule, radiatorType, length, height))
                result.Add((rule.Article, rule.Qty * quantity));
        return result;
    }

    public static IReadOnlyDictionary<string, BracketTotal> CalculateTotal(
        IEnumerable<BracketRadiatorItem> radiatorItems, string? bracketType)
    {
        var totals = new Dictionary<string, BracketTotal>(StringComparer.Ordinal);
        foreach (BracketRadiatorItem item in radiatorItems)
            foreach (var (article, qty) in Calculate(item.RadiatorType, item.Length,
                         item.Height, bracketType, item.Connection, item.Quantity))
            {
                int previous = totals.TryGetValue(article, out var total) ? total.Qty : 0;
                // Keep the key even when the accumulated quantity is zero.
                totals[article] = new BracketTotal(previous + qty);
            }
        return totals;
    }

    private static string GetConnectionGroup(string? connection) => connection switch
    {
        "VK-правое" or "VK-левое" or "K-боковое" => "VK_K",
        "HV-правое" or "HV-левое" or "H-боковое" => "HV_H",
        _ => "VK_K"
    };

    private static string? GetMountType(string? bracketType) => bracketType switch
    {
        "Настенные кронштейны" => "настенный",
        "Напольные кронштейны" => "напольный",
        _ => null
    };

    private static bool Matches(Rule rule, string? radiatorType, int length, int height) =>
        rule.Types.Contains(radiatorType, StringComparer.Ordinal) &&
        rule.LengthMin <= length && length <= rule.LengthMax &&
        rule.HeightMin <= height && height <= rule.HeightMax;

